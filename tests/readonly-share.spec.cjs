test('copy from editor produces clean encoded link and clipboard denial has a fallback',async({page})=>{
 await page.goto('/?view=editor&unrelated=value#old')
 await page.getByRole('button',{name:'暂用浏览器草稿'}).click()
 await page.getByRole('tab',{name:'在线',exact:true}).click()
 await page.getByRole('button',{name,exact:true}).click()
 await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>{window.copiedLink=text}}}))
 await page.getByRole('button',{name:'复制只读链接'}).click()
 const url=new URL(await page.evaluate(()=>window.copiedLink))
 expect(url.searchParams.get('file')).toBe(name);expect(url.searchParams.get('view')).toBe('readonly');expect(url.searchParams.has('unrelated')).toBe(false);expect(url.hash).toBe('')
 await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{value:{writeText:async()=>{throw Error('denied')}}}))
 await page.getByRole('button',{name:'复制只读链接'}).click()
 await expect(page.getByLabel('只读链接',{exact:true})).toHaveValue(url.href)
})
test('bad links and missing files report an error, retry loads current saved version',async({page})=>{
 await expect(page.getByRole('alert')).toContainText('缺少行为文件名')
 await page.goto('/?view=readonly&file=missing.json')
 await expect(page.getByRole('alert')).toContainText('不存在或已改名')
 await page.route('**/data/behaviors/index.json',r=>r.fulfill({status:503}))
 await page.route('**/api/behaviors',r=>r.fulfill({status:503,json:{message:'读取失败，请重试'}}))
 await page.goto('/?view=readonly&file='+encodeURIComponent(name))
 await expect(page.getByRole('alert')).toBeVisible()
 await page.unroute('**/data/behaviors/index.json')
 await page.unroute('**/api/behaviors')
 await page.route('**/api/behaviors',r=>r.fulfill({json:{files:[{name,sha,ref:'b'.repeat(40)}]}}))
 await page.route('**/data/behaviors/index.json',r=>r.fulfill({json:{version:1,files:[{name,sha,size:100}]}}))
 config.behavior.name='最新保存的行为'
 await page.getByRole('button',{name:'重试',exact:true}).click()
 await expect(page.getByRole('heading',{name:'最新保存的行为'})).toBeVisible()
})
