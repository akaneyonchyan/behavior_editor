const {test,expect}=require('@playwright/test')
test('wait countdown updates in place and completed waits remain filterable',async({page})=>{
 await page.goto('/?view=preview');await expect(page.getByRole('button',{name:'开始',exact:true})).toBeEnabled()
 await page.evaluate(async()=>{
  const React=(await import('/node_modules/.vite/deps/react.js')).default
  const {createRoot}=(await import('/node_modules/.vite/deps/react-dom_client.js')).default
  const {default:Panel}=await import('/src/preview/ExperiencePanel.jsx')
  const {syncWaiting}=await import('/src/preview/experience.mjs')
  const controller={actor:'pip',elapsed:10,status:'waiting',waitReason:'',experiences:[]}
  const host=document.createElement('div');host.className='behavior-preview';host.style.width='320px';document.body.replaceChildren(host);const root=createRoot(host)
  window.updateWait=(reason,status='waiting')=>{controller.elapsed++;controller.waitReason=reason;controller.status=status;syncWaiting(controller);root.render(React.createElement(Panel,{controller,revision:controller.elapsed}))}
  window.updateWait('')
 })
 await expect(page.locator('.experience-card')).toHaveCount(0)
 await page.evaluate(()=>window.updateWait('恢复精力冷却剩余 10 分钟'))
 await expect(page.locator('.experience-card')).toHaveCount(1)
 await expect(page.getByRole('heading',{name:'等待目标冷却结束'})).toBeVisible()
 const id=await page.locator('.experience-card').getAttribute('id')
 await page.evaluate(()=>window.updateWait('恢复精力冷却剩余 9 分钟'))
 await expect(page.locator('.experience-card')).toHaveAttribute('id',id)
 await expect(page.locator('.experience-reason')).toContainText('9 分钟')
 await expect(page.locator('.experience-new')).toHaveCount(0)
 await expect(page.locator('.experience-caption')).toHaveCount(0)
 await page.evaluate(()=>window.updateWait('','running'))
 await page.getByLabel('只看异常与等待').check()
 await expect(page.locator('.experience-card')).toHaveCount(1)
 await expect(page.locator('.experience-status')).toHaveText('等待结束')
})
