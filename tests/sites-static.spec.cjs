const {test,expect}=require('@playwright/test')
const {readFileSync}=require('node:fs')
test('Sites artifact loads real snapshots with platform cookie and no cloud API',async({page,context})=>{
 const invalid=[],data=[]
 await context.addCookies([{name:'sites_test_session',value:'fixture',url:'http://127.0.0.1:5198'}])
 page.on('request',r=>{if(['/api/','api.github.com','behavior-editor.online'].some(s=>r.url().includes(s)))invalid.push(r.url());if(r.url().includes('/data/behaviors/'))data.push(r)})
 await page.goto('/?view=editor')
 await page.getByRole('button',{name:'暂用浏览器草稿'}).click()
 await page.getByRole('tab',{name:'在线',exact:true}).click()
 const files=page.locator('.online-files .behavior-file')
 const manifest=JSON.parse(readFileSync('dist/data/behaviors/index.json','utf8'))
 expect(manifest.files.length).toBeGreaterThan(0)
 await expect(files).toHaveCount(manifest.files.length)
 await expect(page.getByRole('button',{name:'上传文件',exact:true})).toHaveCount(0)
 await expect(page.getByRole('button',{name:'上传授权',exact:true})).toHaveCount(0)
 await files.first().click()
 await expect(page.getByRole('region',{name:'在线行为只读画布'})).toBeVisible()
 await expect(page.getByRole('button',{name:'另存为',exact:true})).toBeEnabled()
 for(const request of data)expect((await request.allHeaders()).cookie).toContain('sites_test_session=fixture')
 expect(data.length).toBeGreaterThanOrEqual(2)
 expect(invalid).toEqual([])
})
