const {test,expect}=require('@playwright/test')
test('scene districts and live object state badges',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/?view=preview');await expect(page.getByRole('button',{name:'开始',exact:true})).toBeEnabled()
 await expect(page.locator('.island-zone')).toHaveCount(5)
 await page.screenshot({path:'test-results/island-designed.png'})
 await page.locator('.scene-overview>summary').click()
 await page.getByText(/全部场景对象（/).click()
 await page.locator('.scene-overview-list button').filter({hasText:'桌子'}).click()
 await page.locator('.preview-left').getByRole('spinbutton',{name:'耐久度',exact:true}).fill('0')
 await page.locator('.preview-left').getByRole('spinbutton',{name:'清洁度',exact:true}).fill('10')
 const label=page.locator('.island-label').filter({hasText:'桌子'})
 await expect(label).toContainText('坏了');await expect(label).toContainText('脏了')
 await expect(page.locator('.selected-object-states')).toContainText('耐久为0')
 await page.locator('.scene-overview>summary').click()
 await page.screenshot({path:'test-results/island-damaged.png'})
 await page.locator('.preview-left').getByRole('spinbutton',{name:'耐久度',exact:true}).fill('100')
 await page.locator('.preview-left').getByRole('spinbutton',{name:'清洁度',exact:true}).fill('100')
 await expect(label).not.toContainText('坏了');await expect(label).not.toContainText('脏了')
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:'test-results/island-mobile.png'})
 expect(errors).toEqual([])
})
