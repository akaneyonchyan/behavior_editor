const {test,expect}=require('@playwright/test')
test('split influence controls preserve custom choices and sync summary after reopen',async({page})=>{
 await page.goto('/?view=editor');await page.getByRole('button',{name:'暂用浏览器草稿'}).click()
 await page.locator('[data-id=template_judge]').click()
 const panel=page.locator('.property-panel')
 await panel.getByRole('button',{name:'+ 添加属性',exact:true}).click()
 await panel.getByRole('combobox',{name:'对象大类',exact:true}).fill('测试对象')
 await panel.getByRole('combobox',{name:'对象子类',exact:true}).fill('测试子类')
 await panel.getByRole('combobox',{name:'判断项',exact:true}).fill('测试判断项')
 const type=panel.getByRole('combobox',{name:'影响类型',exact:true}).first(),rule=panel.getByRole('combobox',{name:'影响规则',exact:true}).first()
 await type.fill('数值低');await rule.fill('允许选中')
 await expect(page.locator('[data-id=template_judge]')).toContainText('数值低 · 允许选中')
 await rule.fill('自定义选择规则');await expect(rule).toHaveClass(/custom-choice/)
 const saved=await page.evaluate(async()=>{const {useBehaviorStore:s}=await import('/src/store/behaviorStore.js');const c=s.getState().exportConfig();s.getState().importConfig(c);return c})
 expect(saved.graph.nodes.find(n=>n.type==='judge').data.branches[0].weightFactors[0].influenceRule).toBe('自定义选择规则')
 await page.locator('[data-id=template_judge]').click();await expect(panel.getByRole('combobox',{name:'影响规则',exact:true}).first()).toHaveValue('自定义选择规则')
 await expect(page.locator('[data-id=template_judge] .custom-choice').filter({hasText:'自定义选择规则'})).toHaveCount(1)
})

