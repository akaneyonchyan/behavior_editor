const {test,expect}=require('@playwright/test')
test('resize split, fit graph, readable zoom and pan without editing',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/?view=preview');await expect(page.getByRole('button',{name:'开始',exact:true})).toBeEnabled()
 await page.getByLabel('预览模式').selectOption('single')
 await page.getByLabel('在线行为').selectOption('钓鱼.json')
 const viewport=page.locator('.trace-viewport'),camera=page.getByTestId('trace-camera'),divider=page.getByRole('separator',{name:'调整场景与行为图比例'})
 await expect(page.locator('[data-node-id]')).not.toHaveCount(0)
 async function allVisible(){return viewport.evaluate(el=>{const v=el.getBoundingClientRect();return [...el.querySelectorAll('[data-node-id] rect')].every(n=>{const r=n.getBoundingClientRect();return r.left>=v.left-1&&r.top>=v.top-1&&r.right<=v.right+1&&r.bottom<=v.bottom+1})})}
 await expect.poll(allVisible).toBe(true)
 const before=await viewport.boundingBox(),d=await divider.boundingBox()
 await page.mouse.move(d.x+d.width/2,d.y+5);await page.mouse.down();await page.mouse.move(d.x+d.width/2,d.y-150,{steps:12});await page.mouse.up()
 await expect.poll(async()=>(await viewport.boundingBox()).height).toBeGreaterThan(before.height+100)
 await expect.poll(allVisible).toBe(true)
 await page.getByRole('button',{name:'100%',exact:true}).click();await expect.poll(()=>camera.evaluate(el=>el.transform.baseVal.consolidate().matrix.a)).toBeCloseTo(1)
 const t=await camera.getAttribute('transform'),v=await viewport.boundingBox()
 await page.mouse.move(v.x+v.width/2,v.y+v.height/2);await page.mouse.down();await page.mouse.move(v.x+v.width/2+70,v.y+v.height/2+40,{steps:5});await page.mouse.up()
 await expect(camera).not.toHaveAttribute('transform',t)
 const pan=await camera.getAttribute('transform');await page.mouse.wheel(0,-200);await expect(camera).not.toHaveAttribute('transform',pan)
 await page.getByRole('button',{name:'适应全图',exact:true}).click();await expect.poll(allVisible).toBe(true)
 await page.getByLabel('在线行为').selectOption('在床上睡觉.json');await expect.poll(allVisible).toBe(true)
 await page.getByRole('button',{name:'开始',exact:true}).click();await page.getByRole('button',{name:'暂停',exact:true}).click();await page.getByRole('button',{name:'定位当前节点'}).click();await expect.poll(()=>camera.evaluate(el=>el.transform.baseVal.consolidate().matrix.a)).toBeCloseTo(1)
 await page.screenshot({path:'test-results/preview-viewport-desktop.png'})
 const ratio=await divider.getAttribute('aria-valuenow');await page.reload();await expect(divider).toHaveAttribute('aria-valuenow',ratio)
 await page.getByLabel('预览模式').selectOption('single')
 await page.setViewportSize({width:390,height:844});await expect.poll(async()=>(await viewport.boundingBox()).height).toBeGreaterThan(40)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 expect(errors).toEqual([])
})
