const {test,expect}=require('@playwright/test')
test.use({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:2})
test('mobile touch viewing keeps the graph read-only at 320, 390 and 430px',async({page},testInfo)=>{
 const name='手机只读验证.json',sha='c'.repeat(40)
 await page.route('**/data/library.json*',r=>r.fulfill({json:{syncedAt:new Date().toISOString(),library:{version:1,objects:[],attributes:[],buffs:[]}}}))
 await page.goto('/?view=readonly')
 const config=await page.evaluate(async()=>{const {blankTemplate}=await import('/src/utils/blankTemplate.js');const c=blankTemplate();c.behavior.name='手机只读查阅测试';return c})
 await page.route('**/data/behaviors/index.json',r=>r.fulfill({json:{version:1,files:[{name,sha}]}}))
 await page.route('**/data/behaviors/'+sha+'.json',r=>r.fulfill({json:config}))
 await page.route('**/api/behaviors',r=>r.fulfill({json:{files:[{name,sha,ref:'d'.repeat(40)}]}}))
 await page.route('**/api/behaviors/file?*',r=>r.fulfill({json:{text:JSON.stringify(config)}}))
 const writes=[];page.on('request',r=>{if(r.method()!=='GET')writes.push(r.url())})
 await page.goto('/?view=readonly&file='+encodeURIComponent(name))
 await expect(page.getByRole('heading',{name:'手机只读查阅测试'})).toBeVisible()
 await expect(page.getByLabel('只读节点配置')).toHaveCount(0)
 await expect(page.locator('.behavior-sidebar,.editor-workspace')).toHaveCount(0)
 await page.getByRole('tab',{name:'连线视图',exact:true}).tap()
 const viewport=page.locator('.react-flow__viewport')
 await expect(page.locator('.react-flow__node')).not.toHaveCount(0)
 const nodeStyles=()=>page.locator('.react-flow__node').evaluateAll(nodes=>nodes.map(n=>[n.dataset.id,n.style.transform]))
 const original=await nodeStyles()
 const cdp=await page.context().newCDPSession(page)
 const bounds=await page.locator('.react-flow__pane').boundingBox()
 const x=Math.round(bounds.x+bounds.width/2),y=Math.round(bounds.y+bounds.height*.4)
 const transform=await viewport.getAttribute('style')
 await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]})
 for(let i=1;i<=6;i++)await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x+i*10,y:y+i*7}]})
 await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
 await expect(viewport).not.toHaveAttribute('style',transform)
 const beforePinch=await viewport.getAttribute('style')
 await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:x-25,y},{x:x+25,y}]})
 for(let i=1;i<=6;i++)await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x-25-i*8,y},{x:x+25+i*8,y}]})
 await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
 await expect(viewport).not.toHaveAttribute('style',beforePinch)
 await page.locator('.react-flow__controls-fitview').tap()
 await page.locator('.react-flow__node').first().tap()
 await page.getByRole('button',{name:'JSON 详情',exact:true}).tap()
 await expect(page.getByLabel('只读节点配置').locator('pre')).not.toBeEmpty()
 await page.getByRole('button',{name:'收起 JSON 详情'}).tap()
 expect(await nodeStyles()).toEqual(original)
 for(const width of [320,390,430]){
  await page.setViewportSize({width,height:844})
  await page.locator('.react-flow__controls-fitview').tap()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  const canvas=await page.locator('.online-preview').boundingBox();expect(canvas.height).toBeGreaterThan(300)
  await expect(page.locator('.react-flow__minimap')).toBeHidden()
  expect((await page.locator('.react-flow__controls-zoomin').boundingBox()).height).toBeGreaterThanOrEqual(40)
  await page.screenshot({path:testInfo.outputPath('phone-'+width+'.png')})
  await page.getByRole('button',{name:'JSON 详情',exact:true}).tap()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  expect(await page.locator('.online-preview').boundingBox()).toEqual(canvas)
  await expect(page.getByRole('button',{name:'收起 JSON 详情'})).toBeVisible()
  await page.screenshot({path:testInfo.outputPath('phone-json-'+width+'.png')})
  await page.getByRole('button',{name:'收起 JSON 详情'}).tap()
 }
 await page.getByRole('tab',{name:'工程视图',exact:true}).tap()
 await expect(page.locator('.structured-canvas')).toBeVisible()
 const collapse=page.getByRole('button',{name:/^折叠循环/}).first()
 if(await collapse.count()){await collapse.tap();await page.getByRole('button',{name:/^展开循环/}).first().tap()}
 await page.screenshot({path:testInfo.outputPath('phone-structure.png')})
 expect(await page.locator('input:not([readonly]),textarea,button').evaluateAll(els=>els.filter(e=>/^(保存|删除|新建|共同编辑|进入在线编辑)$/.test(e.textContent)).length)).toBe(0)
 expect(writes).toEqual([])
})
