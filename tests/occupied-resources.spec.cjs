const {test,expect}=require('@playwright/test')
test('occupancy edits synchronize endings without target configuration',async({page})=>{
 await page.route('**/data/library.json*',r=>r.fulfill({json:{syncedAt:new Date().toISOString(),library:{version:1,objects:[],attributes:[],buffs:[]}}}))
 await page.goto('/');await page.getByRole('button',{name:'暂用浏览器草稿'}).click()
 const select=id=>page.evaluate(async id=>{const {useBehaviorStore:g}=await import('/src/store/behaviorStore.js');g.getState().selectNode(g.getState().nodes.find(n=>n.id===id))},id)
 await select('template_result_1');await page.getByRole('button',{name:'+ 添加占用资源',exact:true}).click()
 await page.getByRole('combobox',{name:'对象大类',exact:true}).fill('测试座位')
 await page.getByRole('combobox',{name:'判断项',exact:true}).fill('座位占用')
 await select('template_end')
 const summary=page.locator('.property-panel').getByLabel('自动释放资源')
 await expect(summary).toContainText('测试座位');await expect(summary).toContainText('座位占用');await expect(summary).toContainText('template_result_1')
 await expect(page.getByLabel('结束目标判定',{exact:true})).toHaveCount(0);await expect(page.getByLabel('结束资源释放',{exact:true})).toHaveCount(0)
 await expect(page.locator('[data-id="template_end"]')).not.toContainText('目标判定')
 await select('template_result_1');await page.getByRole('combobox',{name:'判断项',exact:true}).fill('修改后的占用');await select('template_end');await expect(summary).toContainText('修改后的占用')
 await page.evaluate(async()=>{const {useBehaviorStore:g}=await import('/src/store/behaviorStore.js');g.getState().updateNode('template_result_1',{occupiedResources:[]})})
 await expect(summary).toHaveCount(0);await page.evaluate(async()=>{const {useBehaviorStore:g}=await import('/src/store/behaviorStore.js');g.getState().undo()});await expect(summary).toContainText('修改后的占用')
})

