const {test,expect}=require('@playwright/test')
const fs=require('node:fs')
test('public fishing library supports the corrected source graph',async({page})=>{
 test.skip(!process.env.FISHING_LIBRARY_FIXTURE||!process.env.FISHING_CORE_FIXTURE,'Requires private local acceptance fixtures')
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 const text=fs.readFileSync(process.env.FISHING_CORE_FIXTURE,'utf8'),sha='b'.repeat(40)
 const library=JSON.parse(fs.readFileSync(process.env.FISHING_LIBRARY_FIXTURE,'utf8'))
 await page.route('**/data/library.json',r=>r.fulfill({json:{syncedAt:new Date().toISOString(),library}}))
 await page.route('**/data/behaviors/index.json',r=>r.fulfill({json:{version:1,head:sha,files:[{name:'钓鱼细分-核心行为.json',sha,size:Buffer.byteLength(text)}]}}))
 await page.route('**/data/behaviors/'+sha+'.json',r=>r.fulfill({contentType:'application/json',body:text}))
 await page.goto('/?view=preview')
 await page.getByLabel('预览模式').selectOption('single')
 await expect(page.locator('.preview-issues summary')).toContainText('0 项待处理')
 await expect(page.locator('.preview-issues')).not.toContainText('公共库未支持')
 await page.screenshot({path:'test-results/fishing-public-library.png',fullPage:true})
 expect(errors).toEqual([])
})
