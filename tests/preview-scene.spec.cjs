const {test,expect}=require('@playwright/test')
test('continuous playback moves the actor and advances real graph',async({page})=>{
 await page.goto('/?view=preview')
 await page.getByLabel('预览模式').selectOption('single')
 await expect(page.locator('select[aria-label="在线行为"] option')).not.toHaveCount(1)
 await expect(page.getByLabel('在线行为',{exact:true})).toHaveValue('在床上睡觉.json')
 await expect(page.getByRole('button',{name:'开始',exact:true})).toBeEnabled()
 const label=page.locator('.island-label.active')
 const start=await label.getAttribute('data-world-x')
 await page.getByRole('spinbutton',{name:'精力',exact:true}).fill('50')
 await page.getByRole('button',{name:'开始',exact:true}).click()
 await expect(page.getByRole('button',{name:'暂停',exact:true})).toBeVisible()
 await expect.poll(()=>label.getAttribute('data-world-x')).not.toBe(start)
 await expect(page.locator('.current-action h3')).not.toHaveText('开始',{timeout:15000})
 await page.getByLabel('播放倍速').selectOption('60')
 await expect(page.locator('.preview-toolbar')).toContainText('已结束',{timeout:45000})
 await page.getByLabel('在线行为',{exact:true}).selectOption('钓鱼.json')
 await page.getByRole('button',{name:'开始',exact:true}).click()
 await expect(page.locator('.preview-error')).toContainText('准入条件不满足')
 await expect(page.getByRole('button',{name:'暂停',exact:true})).toHaveCount(0)
})
