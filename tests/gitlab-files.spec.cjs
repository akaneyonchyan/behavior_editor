const {test,expect}=require('@playwright/test')
test.beforeEach(async({},testInfo)=>{test.skip(!testInfo.config.metadata.gitlab,'仅在 GitLab 构建模式运行')})
test('GitLab preview stays read-only, refresh sees new files, retry keeps request id and no token UI',async({page})=>{
 const sha='a'.repeat(40),head='b'.repeat(40);let config,files=[{name:'sample.json',sha,ref:head}],requests=[],attempts=0
 await page.route('**/data/library.json*',r=>r.fulfill({json:{syncedAt:new Date().toISOString(),library:{version:1,objects:[],attributes:[],buffs:[]}}}))
 await page.route('**/api/behaviors**',r=>{
  const url=new URL(r.request().url())
  if(url.pathname.endsWith('/uploads')){
   requests.push(r.request().postDataJSON());attempts++
   return attempts===1?r.fulfill({status:502,json:{message:'分支已提交，可在当前窗口重试',recoveryUrl:'https://git.xindong.com/petpals/shared/design_behavior_editor/-/tree/test'}}):r.fulfill({json:{number:12,url:'https://git.xindong.com/petpals/shared/design_behavior_editor/-/merge_requests/12'}})
  }
  if(url.pathname.endsWith('/file'))return r.fulfill({json:{text:JSON.stringify(config)}})
  return r.fulfill({json:{version:1,head,branch:'master',files}})
 })
 await page.goto('/?view=editor')
 await page.getByRole('button',{name:'暂用浏览器草稿'}).click()
 config=await page.evaluate(async()=>{const {blankTemplate}=await import('/src/utils/blankTemplate.js');return blankTemplate()})
 const before=await page.evaluate(async()=>{const {useBehaviorStore}=await import('/src/store/behaviorStore.js');return useBehaviorStore.getState().exportConfig()})
 await page.getByRole('tab',{name:'在线',exact:true}).click()
 await expect(page.getByLabel('GitHub Token')).toHaveCount(0)
 await expect(page.getByRole('button',{name:'上传授权'})).toHaveCount(0)
 await page.getByRole('button',{name:'sample.json',exact:true}).click()
 await expect(page.getByRole('region',{name:'在线行为只读画布'})).toBeVisible()
 await expect(page.getByRole('button',{name:'保存',exact:true})).toBeDisabled()
 await expect(page.getByRole('button',{name:'另存为',exact:true})).toBeEnabled()
 expect(await page.evaluate(async()=>{const {useBehaviorStore}=await import('/src/store/behaviorStore.js');return useBehaviorStore.getState().exportConfig()})).toEqual(before)
 files.push({name:'new.json',sha,ref:head})
 await page.getByRole('region',{name:'在线行为文件'}).getByRole('button',{name:'刷新',exact:true}).click()
 await expect(page.getByRole('button',{name:'new.json',exact:true})).toBeVisible()
 await page.getByLabel('选择上传行为文件').setInputFiles({name:'sample.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(config))})
 const dialog=page.getByRole('dialog',{name:'确认提交行为文件'})
 await expect(dialog).toContainText('提交到项目仓库')
 await dialog.getByRole('button',{name:'创建分支并提交审核'}).click()
 await expect(dialog.getByRole('alert')).toContainText('当前窗口重试')
 await dialog.getByRole('button',{name:'创建分支并提交审核'}).click()
 await expect(dialog).toHaveCount(0)
 await expect(page.getByRole('link',{name:'查看并审核 MR #12'})).toBeVisible()
 expect(requests).toHaveLength(2)
 expect(requests[0].requestId).toEqual(requests[1].requestId)
 expect(requests[0].items[0].previousSha).toEqual(sha)
})
