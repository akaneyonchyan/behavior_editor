const {test,expect}=require('@playwright/test')
test.beforeEach(async({page})=>{
 await page.route('**/data/library.json*',r=>r.fulfill({json:{syncedAt:new Date().toISOString(),library:{version:1,objects:[],attributes:[],buffs:[]}}}))
 await page.addInitScript(()=>localStorage.setItem('pps-canvas-view','structure'))
 await page.goto('/');await page.getByRole('button',{name:'暂用浏览器草稿'}).click()
 await expect(page.locator('.loop-scope')).toHaveCount(1)
})
test('single loop header, inline conditions, centered execution port and no placeholder or return wires',async({page},info)=>{
 await expect(page.getByRole('tablist',{name:'画布视图'}).getByRole('tab').first()).toHaveText('连线视图')
 await expect(page.locator('.react-flow__node-loop')).toHaveCount(0)
 await page.getByLabel('容器循环执行条件').selectOption('count')
 await page.getByLabel('容器最大次数').fill('3')
 await page.locator('.scope-title').click()
 await expect(page.getByLabel('循环执行条件',{exact:true})).toHaveValue('count')
 await expect(page.getByLabel('最大次数',{exact:true})).toHaveValue('3')
 await expect(page.getByLabel('启用准入检查')).toHaveCount(0);await expect(page.getByLabel('启用稍息判定')).toHaveCount(0)
 await page.getByLabel('循环执行条件',{exact:true}).selectOption('goal')
 await expect(page.getByLabel('容器循环执行条件')).toHaveValue('goal')
 await expect(page.locator('.react-flow__edge[data-id="template_wait_next"]')).toHaveCount(0)
 const result=page.locator('[data-id=template_result_1]')
 await expect(result.locator('.node-branch')).toHaveCount(0)
 await expect.poll(async()=>result.evaluate(el=>{
  const node=el.querySelector('.behavior-node').getBoundingClientRect(),port=el.querySelector('.react-flow__handle.source').getBoundingClientRect()
  return Math.abs((port.top+port.height/2)-(node.top+node.height/2))<2&&Math.abs(port.left+port.width/2-node.right)<3
 })).toBe(true)
 await page.waitForTimeout(400);await page.screenshot({path:info.outputPath('loop-container.png')})
 await page.getByRole('tab',{name:'连线视图',exact:true}).click()
 await expect(page.locator('[data-id=template_loop]')).toContainText('执行条件')
 await expect(page.locator('[data-id=template_loop] [data-handleid=rest]')).toHaveCount(0)
})
test('legacy stages become internal nodes explicitly and are undoable',async({page})=>{
 await page.evaluate(async()=>{const {blankTemplate}=await import('/tests/fixtures/legacyTemplate.js');const {useBehaviorStore:g}=await import('/src/store/behaviorStore.js');g.getState().importConfig(blankTemplate())})
 await page.locator('.scope-title').click()
 await page.getByRole('button',{name:'拆分为循环容器与内部节点'}).click()
 await expect(page.getByLabel('循环执行条件',{exact:true})).toBeVisible()
 await expect(page.locator('.react-flow__node-judge')).toHaveCount(3)
 await expect(page.locator('.react-flow__node-loop')).toHaveCount(0)
 await expect(page.locator('.loop-scope')).toHaveCount(1)
 await page.getByRole('button',{name:'撤销',exact:true}).click()
 await expect(page.getByRole('button',{name:'拆分为循环容器与内部节点'})).toBeVisible()
 await expect(page.locator('.react-flow__node-judge')).toHaveCount(1)
})
