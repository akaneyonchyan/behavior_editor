const {test,expect}=require('@playwright/test')
const fs=require('node:fs')
test('detailed fishing accepts the corrected graph and runs in the browser',async({page})=>{
 test.skip(!process.env.FISHING_CORE_FIXTURE,'Set FISHING_CORE_FIXTURE to a local designer JSON; private source is not committed.')
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 const text=fs.readFileSync(process.env.FISHING_CORE_FIXTURE,'utf8'),sha='a'.repeat(40)
 await page.route('**/data/behaviors/index.json',r=>r.fulfill({json:{version:1,head:sha,files:[{name:'钓鱼细分-核心行为.json',sha,size:Buffer.byteLength(text)}]}}))
 await page.route('**/data/behaviors/'+sha+'.json',r=>r.fulfill({contentType:'application/json',body:text}))
 await page.goto('/?view=preview')
 await page.getByLabel('预览模式').selectOption('single')
 await expect(page.locator('.preview-issues summary')).toContainText('0 项待处理')
 await page.getByRole('button',{name:'配置',exact:true}).click()
 await expect(page.getByText('本图预览补值与解释',{exact:true})).toBeVisible()
 await expect(page.getByText(/目标经验30、完整提竿4次/)).toBeVisible()
 await page.getByLabel('播放倍速').selectOption('60')
 await page.getByRole('button',{name:'开始',exact:true}).click()
 await expect(page.locator('.preview-toolbar')).toContainText('已结束',{timeout:50000})
 await expect(page.locator('.preview-error')).toHaveCount(0)
 await page.screenshot({path:'test-results/fishing-core-preview.png',fullPage:true})
 expect(errors).toEqual([])
})
