const {test,expect}=require('@playwright/test')
test('login gate, logout CSRF, online cache removal and local draft preservation',async({page})=>{
 let allowed=false,loggedOut=false
 await page.route('**/api/auth/session',route=>route.fulfill({status:allowed?200:401,json:allowed?{user:{displayName:'测试成员'},role:'viewer',csrfToken:'test-csrf'}:{code:'AUTH_REQUIRED'}}))
 await page.route('**/data/library.json*',route=>route.fulfill({json:{syncedAt:new Date().toISOString(),library:{version:1,objects:[],attributes:[],buffs:[],items:[]}}}))
 await page.route('**/api/behaviors',route=>route.fulfill({json:{version:1,head:'a'.repeat(40),files:[]}}))
 await page.route('**/api/auth/logout',route=>{expect(route.request().headers()['x-csrf-token']).toBe('test-csrf');allowed=false;loggedOut=true;return route.fulfill({status:204})})
 await page.goto('/?view=editor')
 await expect(page.getByRole('link',{name:'在新窗口登录，完成后返回此页'})).toBeVisible()
 await expect(page.locator('.app')).toHaveCount(0)
 allowed=true;await page.evaluate(()=>window.dispatchEvent(new Event('focus')))
 await expect(page.getByText('测试成员',{exact:true})).toBeVisible()
 await expect(page.locator('.app')).toBeVisible()
 await page.getByRole('button',{name:'暂用浏览器草稿'}).click()
 await page.evaluate(()=>{localStorage.setItem('local-draft-test','preserved');localStorage.setItem('pps-published-library-v1','private')})
 await page.getByRole('button',{name:'退出飞书登录'}).click()
 await expect(page.locator('.app')).toHaveCount(0)
 expect(loggedOut).toBe(true)
 expect(await page.evaluate(()=>localStorage.getItem('pps-published-library-v1'))).toBe(null)
 expect(await page.evaluate(()=>localStorage.getItem('local-draft-test'))).toBe('preserved')
})
