const {test,expect}=require('@playwright/test')
test.beforeEach(async()=>test.skip(!process.env.SNAPSHOT_BROWSER_TEST,'Snapshot mode only'))
test('snapshot cloud has read-only preview and no upload or Git token controls',async({page})=>{
 let config;const requests=[]
 page.on('request',r=>{if(/git.xindong.com|api.github.com/.test(r.url()))requests.push(r.url())})
 await page.route('**/data/library.json*',r=>r.fulfill({json:{syncedAt:new Date().toISOString(),library:{version:1,objects:[],attributes:[],buffs:[]}}}))
 await page.route('**/api/behaviors**',r=>r.fulfill({json:r.request().url().includes('/file?')?{text:JSON.stringify(config)}:{version:1,head:'a'.repeat(40),branch:'master',files:[{name:'sample.json',sha:'b'.repeat(40),ref:'a'.repeat(40)}]}}))
 await page.goto('/?view=editor');await page.getByRole('button',{name:'暂用浏览器草稿'}).click()
 config=await page.evaluate(async()=>{const {blankTemplate}=await import('/src/utils/blankTemplate.js');return blankTemplate()})
 await page.getByRole('tab',{name:'在线',exact:true}).click()
 await expect(page.getByRole('button',{name:'上传文件',exact:true})).toHaveCount(0)
 await expect(page.getByRole('button',{name:'上传授权',exact:true})).toHaveCount(0)
 await expect(page.getByText('已发布快照 · 在线只读 · GitLab 更新需重新发布')).toBeVisible()
 await page.getByRole('button',{name:'sample.json',exact:true}).click()
 await expect(page.getByRole('region',{name:'在线行为只读画布'})).toBeVisible()
 await expect(page.getByRole('button',{name:'保存',exact:true})).toBeDisabled()
 await expect(page.getByRole('button',{name:'另存为',exact:true})).toBeEnabled()
 expect(requests).toEqual([])
})
