const {test,expect}=require('@playwright/test')
test('24h of real online graphs, state and timed buffs',async({page})=>{
 test.setTimeout(120000);const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/?view=preview');await expect(page.getByRole('button',{name:'开始',exact:true})).toBeEnabled()
 await page.getByLabel('预览模式').selectOption('auto')
 for(const name of ['斑斑','娜娜','裴洛','芬恩','古奶奶'])await page.getByLabel('启用'+name).uncheck()
 const result=await page.evaluate(async()=>{
  const {parseBehavior}=await import('/src/utils/onlineBehaviors.js'),{GoalScheduler,makeScenarioWorld}=await import('/src/preview/scheduler.mjs')
  const lib=(await(await fetch('/data/library.json')).json()).library,index=await(await fetch('/data/behaviors/index.json')).json()
  const files=await Promise.all(index.files.map(async f=>({...f,config:parseBehavior(await(await fetch('/data/behaviors/'+f.sha+'.json')).text())})))
  const s=new GoalScheduler(files,lib,makeScenarioWorld(lib,undefined,files),'pip',{}, {dayMode:true})
  for(let i=0;i<1440;i++)s.tick(1)
  return {status:s.status,elapsed:s.elapsed,stats:s.statistics,completed:s.completed,logs:s.logs,candidates:s.candidates.map(c=>({name:c.file.name,reasons:c.reasons}))}
 })
 console.log(JSON.stringify({status:result.status,elapsed:result.elapsed,stats:result.stats}))
 expect(result.status).toBe('day-complete');expect(result.elapsed).toBe(1440)
 expect(Object.keys(result.stats).length).toBeGreaterThanOrEqual(4)
 expect(result.completed.filter(c=>c.status==='done').length).toBeGreaterThan(10)
 await page.getByLabel('播放倍速').selectOption('60');await page.getByRole('button',{name:'开始',exact:true}).click()
 await expect(page.locator('.preview-toolbar')).toContainText('观察结束',{timeout:60000})
 await expect(page.locator('.preview-toolbar')).toContainText('第2天 00:00')
 await page.screenshot({path:'test-results/preview-day.png'})
 expect(errors).toEqual([])
})
