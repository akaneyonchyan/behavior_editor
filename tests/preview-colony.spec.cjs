const {test,expect}=require('@playwright/test')
test('six actor toggles, active Buff filter and fixed orthographic camera',async({page})=>{
 test.setTimeout(90000);const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/?view=preview');await expect(page.getByRole('button',{name:'开始',exact:true})).toBeEnabled()
 const island=page.getByLabel('行为预览小岛')
 await expect(island).toHaveAttribute('data-camera-kind','orthographic')
 const rotation=await island.getAttribute('data-camera-rotation'),pos=await island.getAttribute('data-camera-position'),box=await island.boundingBox()
 await page.mouse.move(box.x+25,box.y+30);await page.mouse.down();await page.mouse.move(box.x+85,box.y+50,{steps:5});await page.mouse.up()
 await expect(island).not.toHaveAttribute('data-camera-position',pos)
 let previous=''
 await expect.poll(async()=>{const value=(await island.getAttribute('data-camera-position')).split(',').map(v=>Number(v).toFixed(3)).join(',');const settled=value===previous;previous=value;return settled}).toBe(true)
 const panned=await island.getAttribute('data-camera-position')
 await page.mouse.down({button:'right'});await page.mouse.move(box.x+140,box.y+80,{steps:5});await page.mouse.up({button:'right'})
 await expect.poll(async()=>Math.max(...(await island.getAttribute('data-camera-position')).split(',').map((v,i)=>Math.abs(Number(v)-Number(panned.split(',')[i]))))).toBeLessThan(.01)
 await expect(island).toHaveAttribute('data-camera-rotation',rotation)
 const zoom=await island.getAttribute('data-camera-zoom');await page.mouse.wheel(0,-200);await expect(island).not.toHaveAttribute('data-camera-zoom',zoom)
 await expect(page.locator('.preview-left summary').filter({hasText:/^Buff/})).toHaveText('Buff（0）')
 await page.getByLabel('启用娜娜').uncheck();await expect(island.locator('.island-label').filter({hasText:/^娜娜/})).toHaveCount(0)
 await page.getByLabel('启用娜娜').check();await expect(island.locator('.island-label').filter({hasText:/^娜娜/})).toHaveCount(1)
 await page.getByLabel('播放倍速').selectOption('60');await page.getByRole('button',{name:'开始',exact:true}).click()
 await expect(island.locator('.island-label').filter({hasText:/^芬恩.*▶/})).toHaveCount(1)
 await page.getByLabel('启用皮普').uncheck();await expect(island.locator('.island-label').filter({hasText:/^皮普/})).toHaveCount(0)
 await page.getByRole('combobox').filter({has:page.locator('option[value="finn"]')}).selectOption('finn')
 await expect(page.locator('.current-action')).not.toContainText('等待开始')
 await page.getByRole('button',{name:'暂停',exact:true}).click()
 await page.screenshot({path:'test-results/preview-colony.png'})
 expect(errors).toEqual([])
})
