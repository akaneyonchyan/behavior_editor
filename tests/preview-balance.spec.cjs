const {test,expect}=require('@playwright/test')
test('unified online graph simulation displays workbook-derived rhythm',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/?view=preview');await expect(page.getByRole('button',{name:'开始',exact:true})).toBeEnabled()
 await expect(page.getByLabel('预览模式')).toHaveValue('auto')
 await expect(page.getByLabel('预览模式').locator('option')).toHaveCount(2)
 await expect(page.locator('.balance-timeline')).toHaveCount(0)
 await page.getByLabel('播放倍速').selectOption('20');await page.getByRole('button',{name:'开始',exact:true}).click()
 await expect(page.locator('.goal-panel')).toContainText('数值表负责节奏')
 await expect(page.locator('.preview-graph [data-node-id]')).not.toHaveCount(0)
 await expect(page.locator('.goal-panel')).toContainText('当前补值',{timeout:20000})
 await page.getByRole('button',{name:'暂停',exact:true}).click()
 await page.locator('.preview-right nav').getByRole('button',{name:'配置',exact:true}).click()
 await expect(page.locator('.preview-right')).toContainText('逐行为补值依据')
 await page.screenshot({path:'test-results/preview-rhythm.png'})
 await page.getByRole('button',{name:'重置',exact:true}).click()
 await page.getByLabel('预览模式').selectOption('single')
 await page.getByRole('button',{name:'单步',exact:true}).click()
 await page.locator('.preview-right nav').getByRole('button',{name:'记录',exact:true}).click()
 await expect(page.locator('.event-list')).toContainText('数值依据：睡觉')
 expect(errors).toEqual([])
})
