const {test,expect}=require('@playwright/test')
const select=(page,id)=>page.evaluate(async id=>{const {useBehaviorStore:g}=await import('/src/store/behaviorStore.js');g.getState().selectNode(g.getState().nodes.find(n=>n.id===id))},id)
test.beforeEach(async({page})=>{
 await page.route('**/data/library.json*',r=>r.fulfill({json:{syncedAt:new Date().toISOString(),library:{version:1,objects:[],attributes:[],buffs:[]}}}))
 await page.goto('/');await page.getByRole('button',{name:'暂用浏览器草稿'}).click()
 await expect(page.locator('.react-flow__node')).toHaveCount(7)
})
test('external branch labels, no ports, undo, loop toggles, PNG snapshot and reload',async({page})=>{
 await expect(page.locator('.node-palette .palette-node').filter({hasText:'位移'})).toHaveCount(0)
 const loop=page.locator('[data-id=template_loop]')
 await expect(loop.locator('.external-exit')).toContainText('跳出行为')
 await expect(loop.locator('[data-handleid=insufficient]')).toHaveCount(0)
 await select(page,'template_judge')
 await page.getByLabel('分支1后续去向类型',{exact:true}).selectOption('external')
 await page.getByLabel('分支1后续去向跳出说明',{exact:true}).fill('交回外部通用流程')
 const judge=page.locator('[data-id=template_judge]')
 await expect(judge.locator('.external-exit')).toContainText('交回外部通用流程')
 await expect(judge.locator('[data-handleid=branch_1]')).toHaveCount(0)
 await page.getByLabel('分支1后续去向类型',{exact:true}).selectOption('node')
 await expect(judge.locator('[data-handleid=branch_1]')).toHaveCount(1)
 await expect(page.getByLabel('分支1后续去向',{exact:true})).toHaveValue('')
 await page.evaluate(async()=>{const {useBehaviorStore:g}=await import('/src/store/behaviorStore.js');g.getState().undo()})
 await expect(judge.locator('.external-exit')).toContainText('交回外部通用流程')
 await select(page,'template_result_1')
 await page.getByLabel('后续去向类型',{exact:true}).selectOption('external')
 await expect(page.locator('[data-id=template_result_1] .external-exit')).toContainText('跳出行为')
 await select(page,'template_loop')
 await page.getByLabel('启用准入检查',{exact:true}).uncheck()
 await expect(loop.locator('.external-exit')).toHaveCount(0)
 await page.getByLabel('启用准入检查',{exact:true}).check()
 await expect(loop.locator('.external-exit')).toHaveCount(1)
 const snapshot=await page.evaluate(async()=>{const {captureCanvas}=await import('/src/utils/pngExport.js');const {clone}=captureCanvas(document.querySelector('.canvas > .react-flow'),{scale:1});return {labels:[...clone.querySelectorAll('.external-exit')].map(e=>e.textContent),ports:clone.querySelectorAll('.react-flow__handle').length}})
 expect(snapshot.labels).toHaveLength(3);expect(snapshot.labels.join('')).toContain('交回外部通用流程');expect(snapshot.ports).toBe(0)
 await page.evaluate(async()=>{const {flushDraft}=await import('/src/store/documentSession.js');flushDraft()})
 await page.reload();await expect(page.locator('.external-exit')).toHaveCount(3)
})
