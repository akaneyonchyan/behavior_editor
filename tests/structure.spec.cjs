const {test,expect}=require('@playwright/test')
test.beforeEach(async({page})=>{
 await page.route('**/data/library.json*',r=>r.fulfill({json:{syncedAt:new Date().toISOString(),library:{version:1,objects:[],attributes:[],buffs:[]}}}))
 await page.addInitScript(()=>{localStorage.setItem('pps-canvas-view','structure');window.showSaveFilePicker=undefined})
 await page.goto('/');await page.getByRole('button',{name:'暂用浏览器草稿'}).click()
 await expect(page.locator('.react-flow__node')).toHaveCount(8)
})
const state=page=>page.evaluate(async()=>{const {useBehaviorStore:g}=await import('/src/store/behaviorStore.js');return g.getState().exportConfig()})
test('structure selection, collapse, raw view, isolated expanded PNG and persistent layout',async({page},info)=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 const before=await state(page)
 await expect(page.locator('.scope-title')).toContainText('先判定，再执行')
 await page.locator('[data-id=template_result_1]').click()
 await expect(page.locator('.property-panel')).toContainText('表演')
 await page.getByRole('tab',{name:'连线视图',exact:true}).click()
 await expect(page.locator('.react-flow__node')).toHaveCount(7)
 expect(await state(page)).toEqual(before)
 await page.getByRole('tab',{name:'结构视图',exact:true}).click()
 await page.getByLabel('折叠循环 template_loop').click()
 await expect(page.locator('.react-flow__node')).toHaveCount(3)
 const expanded=await page.evaluate(async()=>{
  const {structureSnapshot}=await import('/src/components/structureSnapshot.jsx'),{useBehaviorStore:g}=await import('/src/store/behaviorStore.js')
  const snap=await structureSnapshot(g.getState())
  const {captureCanvas}=await import('/src/utils/pngExport.js')
  try{const {clone}=captureCanvas(snap.source,{scale:1});return {nodes:clone.querySelectorAll('.react-flow__node').length,buttons:clone.querySelectorAll('[data-export-ignore]').length}}finally{snap.dispose()}
 })
 expect(expanded).toEqual({nodes:8,buttons:0})
 await expect(page.locator('.react-flow__node')).toHaveCount(3)
 expect(await state(page)).toEqual(before)
 await page.getByRole('button',{name:'导出 PNG',exact:true}).click()
 await page.getByLabel('清晰度').selectOption('1')
 const pending=page.waitForEvent('download')
 await page.getByRole('button',{name:'下载 PNG',exact:true}).click()
 await (await pending).saveAs(info.outputPath('structure.png'))
 await expect(page.getByRole('dialog')).toHaveCount(0)
 await expect(page.locator('.react-flow__node')).toHaveCount(3)
 expect(await state(page)).toEqual(before)
 await page.getByLabel('展开循环 template_loop').click()
 await page.waitForTimeout(400)
 await page.screenshot({path:info.outputPath('structure.png.view.png')})
 const title=page.locator('.loop-scope header'),box=await title.boundingBox()
 await page.mouse.move(box.x+box.width/2,box.y+8);await page.mouse.down();await page.mouse.move(box.x+box.width/2+50,box.y+35,{steps:10});await page.mouse.up()
 const moved=await state(page);expect(moved.graph.layout.positions.__scope_template_loop).toBeDefined()
 await page.evaluate(async()=>{const {flushDraft}=await import('/src/store/documentSession.js');flushDraft()})
 await page.reload();await expect(page.locator('.react-flow__node')).toHaveCount(8)
 expect((await state(page)).graph.layout.positions).toEqual(moved.graph.layout.positions)
 expect(errors).toEqual([])
})
test('files convert automatically; online structure remains readonly',async({page})=>{
 await page.evaluate(async()=>{const {useBehaviorStore:g}=await import('/src/store/behaviorStore.js');const {blankTemplate}=await import('/tests/fixtures/legacyTemplate.js');const c=blankTemplate();delete c.graph.layout;delete c.graph.nodes.find(n=>n.type==='loop').data.checkTiming;for(const e of c.graph.edges)if(['behavior_start','template_wait'].includes(e.source))e.target='template_judge';g.getState().importConfig(c)})
 const old=await state(page)
 await page.locator('.scope-title').click()
 await expect(page.locator('.property-panel').getByLabel('结束条件 1 类型',{exact:true})).toBeVisible()
 expect(old.graph.edges.find(e=>e.source==='behavior_start').target).toBe('template_loop')
 expect(old.graph.nodes.find(n=>n.type==='loop').data.loopVersion).toBe(3)
 await expect(page.locator('.property-panel')).not.toContainText('迁移')
 await page.route('**/data/behaviors/index.json',r=>r.fulfill({json:{version:1,files:[{name:'结构测试.json',sha:'a'.repeat(40),size:100}]}}))
 await page.route('**/data/behaviors/'+ 'a'.repeat(40)+'.json',r=>r.fulfill({json:old}))
 await page.getByRole('tab',{name:'在线',exact:true}).click();await page.getByRole('button',{name:'结构测试.json',exact:true}).click()
 await expect(page.locator('.online-structure .loop-scope')).toHaveCount(1)
 await page.locator('.online-structure .scope-title').click()
 await expect(page.locator('.property-panel select')).toHaveCount(0)
 await page.keyboard.press('Delete');expect(await state(page)).toEqual(old)
})
