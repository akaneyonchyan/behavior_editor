const {test,expect}=require('@playwright/test')
test('catalog verification, preparation scene and editor theme',async({page})=>{
 test.setTimeout(120000);const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/?view=preview');await expect(page.getByRole('button',{name:'开始',exact:true})).toBeEnabled()
 await page.getByLabel('预览模式').selectOption('auto')
 await page.getByRole('button',{name:'接入',exact:true}).click()
 await expect(page.locator('.preview-catalog h3')).toContainText('18')
 await page.getByRole('button',{name:'逐张验证当前快照'}).click()
 await expect(page.locator('.preview-catalog')).toContainText('已验证 18 / 18，其中 18 份',{timeout:90000})
 const row=page.locator('.preview-catalog > details').filter({has:page.locator('summary').filter({hasText:'用扳手维修交互物'})})
 await row.locator('summary').first().click();await row.getByRole('button',{name:'新建验证场景'}).click()
 await page.getByLabel('播放倍速').selectOption('20')
 await expect(page.locator('.goal-panel')).toContainText('用扳手维修交互物.json',{timeout:20000})
 const color=await page.locator('.behavior-preview').evaluate(el=>getComputedStyle(el).backgroundColor)
 expect(color).toBe('rgb(5, 7, 12)')
 await page.screenshot({path:'test-results/preview-integration-desktop.png'})
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:'test-results/preview-integration-mobile.png'})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 expect(errors).toEqual([])
})
