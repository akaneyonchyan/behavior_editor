const {test,expect}=require('@playwright/test')
test('online graphs finish and goal policy chooses another graph with persistent state',async({page})=>{
 test.setTimeout(90000)
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/?view=preview')
 await expect(page.getByRole('button',{name:'开始',exact:true})).toBeEnabled()
 await page.getByLabel('预览模式').selectOption('auto')
 for(const name of ['斑斑','娜娜','裴洛','芬恩','古奶奶'])await page.getByLabel('启用'+name).uncheck()
 const audit=await page.evaluate(async()=>{
  const {parseBehavior}=await import('/src/utils/onlineBehaviors.js'),{GoalScheduler,makeScenarioWorld}=await import('/src/preview/scheduler.mjs')
  const lib=(await(await fetch('/data/library.json')).json()).library,index=await(await fetch('/data/behaviors/index.json')).json()
  const files=await Promise.all(index.files.map(async f=>({...f,config:parseBehavior(await(await fetch('/data/behaviors/'+f.sha+'.json')).text())})))
  const s=new GoalScheduler(files,lib,makeScenarioWorld(lib,undefined,files),'pip',{seconds:.1})
  for(let i=0;i<3000;i++)s.tick(.2)
  return {completed:s.completed,attrs:s.world.find(o=>o.id==='pip').attrs,logs:s.logs,candidates:s.candidates.map(c=>({name:c.file.name,reasons:c.reasons}))}
 })
 console.log(JSON.stringify({completed:audit.completed,energy:audit.attrs.energy,cleanliness:audit.attrs.cleanliness}))
 expect(audit.completed.some(c=>c.file==='在床上睡觉.json'&&c.status==='done')).toBeTruthy()
 expect(audit.completed.some(c=>c.file==='洗手池清洗自己.json'&&c.status==='done')).toBeTruthy()
 expect(audit.attrs.energy).toBeGreaterThanOrEqual(70);expect(audit.attrs.cleanliness).toBeGreaterThanOrEqual(70)
 await page.getByLabel('播放倍速').selectOption('60')
 await page.getByRole('button',{name:'开始',exact:true}).click()
 await expect(page.locator('.goal-panel')).toBeVisible()
 await expect(page.locator('.goal-panel')).toContainText('当前补值',{timeout:30000})
 await page.getByRole('button',{name:'暂停',exact:true}).click()
 await expect(page.locator('.preview-toolbar')).toContainText('已暂停')
 await page.locator('.preview-right nav').getByRole('button',{name:'记录',exact:true}).click()
 await expect(page.locator('.event-list')).toContainText('数值表最高分')
 await expect(page.locator('.event-list')).toContainText('节奏表补值')
 await page.locator('.preview-right nav').getByRole('button',{name:'目标',exact:true}).click()
 await page.screenshot({path:'test-results/preview-goals.png'})
 await page.getByRole('button',{name:'重置',exact:true}).click()
 await expect(page.locator('.goal-panel')).toContainText('等待开始')
 expect(errors).toEqual([])
})
